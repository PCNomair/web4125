#!/usr/bin/env node
/**
 * Builds src/fonts.generated.ts from the files in fonts/.
 *
 * Why: a page designed on Windows says `font-family: Tahoma, Arial, sans-serif`.
 * Linux runners have neither, so Chrome silently substituted DejaVu and every
 * line box, weight and letter-spacing changed — the "the font changed and the
 * sizes are wrong" bug.
 *
 * Fix: register the family names the page asks for *inside the page itself* with
 * @font-face, pointing at fonts we ship. `unicode-range` splits Arabic from Latin
 * so one family name keeps full coverage.
 *
 * Drop a real `fonts/Tahoma.ttf` (or Arial/SegoeUI/Trebuchet/Verdana) in here and
 * it becomes the primary face for that family automatically.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const FONT_DIR = path.join(ROOT, 'fonts');
const OUT_FILE = path.join(ROOT, 'src', 'fonts.generated.ts');

const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215';
const ARABIC = 'U+0600-06FF,U+0750-077F,U+0870-088E,U+08A0-08FF,U+200C-200E,U+FB50-FDFF,U+FE70-FEFF';

/** Page family name → which shipped file covers Latin / Arabic */
const ALIASES = ['Tahoma', 'Arial', 'Helvetica', 'Segoe UI', 'Trebuchet MS', 'Verdana', 'system-ui'];

const FALLBACK = {
  latin: { regular: 'LiberationSans-Regular.ttf', bold: 'LiberationSans-Bold.ttf' },
  arabic: { regular: 'NotoSansArabic-Regular.ttf', bold: 'NotoSansArabic-Bold.ttf' },
};

const files = fs.existsSync(FONT_DIR)
  ? fs.readdirSync(FONT_DIR).filter((f) => /\.(ttf|otf|woff2?)$/i.test(f))
  : [];

// resolved to an absolute URL at render time (see src/timeline.ts)
const url = (file) => `__FONT_BASE__${file}`;
const rules = [];

// 1. Real font files supplied by the user (wins over the bundled substitute).
for (const file of files) {
  const base = file.toLowerCase();
  const family = ALIASES.find((name) => base.startsWith(name.toLowerCase().replace(/\s+/g, '')));
  if (!family) continue;
  const weight = /bold|bd|700/.test(base) ? 700 : 400;
  rules.push(
    `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:block;src:url('${url(
      file,
    )}') format('${file.toLowerCase().endsWith('.otf') ? 'opentype' : 'truetype'}');}`,
  );
}

const customFamilies = new Set(
  rules.map((r) => r.slice(0, r.indexOf("';")).replace("@font-face{font-family:'", '')),
);

// 2. Split aliases for every family that has no real file: same name, two scripts.
for (const family of ALIASES) {
  if (customFamilies.has(family)) continue;
  for (const weight of [400, 700]) {
    const key = weight === 700 ? 'bold' : 'regular';
    rules.push(
      `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:block;` +
        `src:url('${url(FALLBACK.latin[key])}') format('truetype');unicode-range:${LATIN};}`,
    );
    rules.push(
      `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:block;` +
        `src:url('${url(FALLBACK.arabic[key])}') format('truetype');unicode-range:${ARABIC};}`,
    );
  }
}

const css = `/* AUTO-GENERATED by scripts/scan-fonts.mjs — do not edit. */
export const FONT_ALIASES = ${JSON.stringify(ALIASES)};
export const CUSTOM_FONTS = ${JSON.stringify([...customFamilies])};
export const FONT_CSS = ${JSON.stringify(rules.join('\n'))};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, css);

console.log(
  `[fonts] ${rules.length} @font-face rule(s) for ${ALIASES.length} families` +
    (customFamilies.size ? ` (custom: ${[...customFamilies].join(', ')})` : ' (bundled substitutes)'),
);
