#!/usr/bin/env node
/**
 * Scans every .html file under public/scenes/ (sub-folders included) and writes
 * src/scenes.generated.ts.
 * Every .html file inside public/scenes/ becomes one Remotion composition and
 * therefore one MP4. Sub-folders are allowed (the id is built from the path).
 * A matching audio file in public/audio/ is attached automatically:
 *   public/scenes/promo.html  +  public/audio/promo.mp3  ->  promo.mp4 with sound
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const SCENES_DIR = path.join(ROOT, 'public', 'scenes');
const AUDIO_DIR = path.join(ROOT, 'public', 'audio');
const OUT_FILE = path.join(ROOT, 'src', 'scenes.generated.ts');
const AUDIO_EXT = ['.mp3', '.wav', '.m4a', '.aac', '.ogg', '.flac'];

const posix = (p) => p.split(path.sep).join('/');

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else if (entry.isFile() && entry.name.toLowerCase().endsWith('.html')) out.push(full);
  }
  return out;
}

function slug(input) {
  return input
    .toLowerCase()
    .replace(/\.html$/, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'scene';
}

const files = walk(SCENES_DIR).sort((a, b) => a.localeCompare(b));
const used = new Map();

const scenes = files.map((file) => {
  const rel = posix(path.relative(SCENES_DIR, file));
  let id = `scene-${slug(rel)}`;
  if (used.has(id)) {
    used.set(id, used.get(id) + 1);
    id = `${id}-${used.get(id)}`;
  } else {
    used.set(id, 1);
  }

  const base = rel.replace(/\.html$/i, '');
  let audio = null;
  for (const ext of AUDIO_EXT) {
    const candidate = path.join(AUDIO_DIR, `${base}${ext}`);
    if (fs.existsSync(candidate)) {
      audio = `audio/${base}${ext}`;
      break;
    }
  }

  return { id, file: `scenes/${rel}`, audio, title: path.basename(rel) };
});

// fonts/ ships with the repo and must be reachable from the iframe
const FONT_SRC = path.join(ROOT, 'fonts');
const FONT_DEST = path.join(ROOT, 'public', 'fonts');
if (fs.existsSync(FONT_SRC)) {
  fs.mkdirSync(FONT_DEST, { recursive: true });
  for (const file of fs.readdirSync(FONT_SRC)) {
    if (!/\.(ttf|otf|woff2?)$/i.test(file)) continue;
    fs.copyFileSync(path.join(FONT_SRC, file), path.join(FONT_DEST, file));
  }
  const count = fs.readdirSync(FONT_DEST).length;
  console.log(`[scan] ${count} font file(s) → public/fonts/`);
}

const banner = `// AUTO-GENERATED by scripts/scan-scenes.mjs — do not edit.
// Re-generated automatically by \`npm run scan\`, \`npm run render\` and CI.
export type Scene = {
  id: string;
  /** Path inside public/ — feed it to staticFile() */
  file: string;
  audio: string | null;
  title: string;
};

export const SCENES: Scene[] = ${JSON.stringify(scenes, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, banner);

if (scenes.length === 0) {
  console.warn(
    '\n[scan] No HTML files found in public/scenes/.\n' +
      '[scan] Add at least one .html file (see public/scenes/demo.html for an example).\n',
  );
} else {
  console.log(`[scan] ${scenes.length} scene(s):`);
  for (const s of scenes) {
    console.log(`  • ${s.file}${s.audio ? `  +  ${s.audio}` : ''}   (id: ${s.id})`);
  }
}
