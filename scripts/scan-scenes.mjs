#!/usr/bin/env node
/**
 * Scans HTML videos mirrored into public/scenes/ and React video inputs in inputs/.
 * Each HTML or default-exported TSX input becomes a Remotion composition.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const INPUTS_DIR = path.join(ROOT, 'inputs');
const SCENES_DIR = path.join(ROOT, 'public', 'scenes');
const AUDIO_DIR = path.join(ROOT, 'public', 'audio');
const OUT_FILE = path.join(ROOT, 'src', 'scenes.generated.ts');
const AUDIO_EXT = ['.mp3', '.wav', '.m4a', '.aac', '.ogg', '.flac'];

const posix = (p) => p.split(path.sep).join('/');

function walk(dir, extensions) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full, extensions));
    else if (entry.isFile() && extensions.includes(path.extname(entry.name).toLowerCase())) out.push(full);
  }
  return out;
}

function slug(input) {
  return input
    .toLowerCase()
    .replace(/\.(html|tsx)$/i, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'scene';
}

function uniqueId(prefix, rel, used) {
  const base = `${prefix}${slug(rel)}`;
  let id = base;
  let suffix = 2;
  while (used.has(id)) id = `${base}-${suffix++}`;
  used.add(id);
  return id;
}

const used = new Set();

// Treat inputs/ as the source of truth for HTML and audio as well as TSX.
// Copy HTML into public/scenes/ because Remotion's staticFile() serves public/.
const htmlFiles = walk(INPUTS_DIR, ['.html'])
  .filter((file) => posix(path.relative(INPUTS_DIR, file)).split('/')[0].toLowerCase() !== 'audio')
  .sort((a, b) => a.localeCompare(b));
fs.mkdirSync(SCENES_DIR, { recursive: true });

for (const file of htmlFiles) {
  const rel = posix(path.relative(INPUTS_DIR, file));
  const dest = path.join(SCENES_DIR, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(file, dest);
}

// Refresh audio files so stale tracks from previous renders cannot be attached.
fs.rmSync(AUDIO_DIR, { recursive: true, force: true });
fs.mkdirSync(AUDIO_DIR, { recursive: true });
const inputAudioDir = path.join(INPUTS_DIR, 'audio');
for (const file of walk(inputAudioDir, AUDIO_EXT)) {
  const rel = posix(path.relative(inputAudioDir, file));
  const dest = path.join(AUDIO_DIR, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(file, dest);
}

const scenes = htmlFiles.map((file) => {
  const rel = posix(path.relative(INPUTS_DIR, file));
  const id = uniqueId('scene-', rel, used);
  const base = rel.replace(/\.html$/i, '');
  let audio = null;
  for (const ext of AUDIO_EXT) {
    const candidate = path.join(AUDIO_DIR, `${base}${ext}`);
    if (fs.existsSync(candidate)) {
      audio = `audio/${base}${ext}`;
      break;
    }
  }
  return { id, file: `scenes/${rel}`, audio, title: path.basename(rel) };
});

const tsxFiles = walk(INPUTS_DIR, ['.tsx']).sort((a, b) => a.localeCompare(b));
const reactScenes = tsxFiles.map((file, index) => {
  const rel = posix(path.relative(INPUTS_DIR, file));
  return {
    id: uniqueId('react-', rel, used),
    importName: `InputReactVideo${index}`,
    importPath: `../inputs/${rel.replace(/\.tsx$/i, '')}`,
    title: path.basename(rel),
  };
});

// Fonts ship with the repo and must be reachable from HTML render iframes.
const FONT_SRC = path.join(ROOT, 'fonts');
const FONT_DEST = path.join(ROOT, 'public', 'fonts');
if (fs.existsSync(FONT_SRC)) {
  fs.mkdirSync(FONT_DEST, { recursive: true });
  for (const file of fs.readdirSync(FONT_SRC)) {
    if (!/\.(ttf|otf|woff2?)$/i.test(file)) continue;
    fs.copyFileSync(path.join(FONT_SRC, file), path.join(FONT_DEST, file));
  }
  const count = fs.readdirSync(FONT_DEST).length;
  console.log(`[scan] ${count} font file(s) → public/fonts/`);
}

const reactImports = reactScenes
  .map((scene) => `import ${scene.importName} from ${JSON.stringify(scene.importPath)};`)
  .join('\n');
const reactEntries = reactScenes
  .map((scene) => `  { id: ${JSON.stringify(scene.id)}, component: ${scene.importName}, title: ${JSON.stringify(scene.title)} },`)
  .join('\n');
const reactMetadata = reactScenes.map(({ id, title }) => ({ id, title }));

const banner = `// AUTO-GENERATED by scripts/scan-scenes.mjs — do not edit.
import type { ComponentType } from 'react';
${reactImports ? `\n${reactImports}\n` : ''}
export type Scene = {
  id: string;
  /** Path inside public/ — feed it to staticFile() */
  file: string;
  audio: string | null;
  title: string;
};

export const SCENES: Scene[] = ${JSON.stringify(scenes, null, 2)};

export type ReactScene = {
  id: string;
  component: ComponentType<any>;
  title: string;
};

export const REACT_SCENES: ReactScene[] = [
${reactEntries}
];

export const REACT_SCENE_METADATA = ${JSON.stringify(reactMetadata, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, banner);

if (scenes.length === 0) {
  console.log('[scan] No HTML scenes found in public/scenes/.');
} else {
  console.log(`[scan] ${scenes.length} HTML scene(s):`);
  for (const scene of scenes) {
    console.log(`  • ${scene.file}${scene.audio ? ` + ${scene.audio}` : ''} (id: ${scene.id})`);
  }
}
if (reactScenes.length === 0) {
  console.log('[scan] No React TSX inputs found in inputs/.');
} else {
  console.log(`[scan] ${reactScenes.length} React TSX video(s):`);
  for (const scene of reactScenes) console.log(`  • inputs/${scene.title} (id: ${scene.id})`);
}
